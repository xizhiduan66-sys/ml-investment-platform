"""Export a workbench fixture from the current code and isolated, synthetic OHLCV."""
from contextlib import redirect_stdout
import json
import os
from pathlib import Path
import sys
from tempfile import TemporaryDirectory


def export_fixture():
    import numpy as np
    import pandas as pd
    from quant import data, jobs
    from quant.app import BacktestIn, ExperimentIn, catalog, create_backtest, create_experiment, experiment, preview
    from quant.worker import execute

    random = np.random.default_rng(101)
    close = 100 * np.exp(np.cumsum(random.normal(.0001, .009, 4400)))
    opened = np.r_[close[0], close[:-1]] + random.normal(0, 0.10, len(close))
    frame = pd.DataFrame({
        'date': pd.date_range('2025-01-01', periods=len(close), freq='h', tz='UTC'),
        'open': opened,
        'high': np.maximum(opened, close) + random.uniform(.1, .45, len(close)),
        'low': np.minimum(opened, close) - random.uniform(.1, .45, len(close)),
        'close': close,
        'volume': random.integers(150, 600, len(close)),
    })
    saved = data.persist(frame, '演示行情 · 1h', 'csv', symbol='DEMO', interval='1h')
    snapshot = {key: saved[key] for key in ('name', 'start', 'end', 'rows', 'interval')}
    contents = catalog()
    features = contents['factors'] + contents['chan_event']['features']
    fixture = {
        'snapshot': snapshot,
        'bars': preview(saved['id'])['bars'],
        'features': features,
        'factorSets': contents['factor_sets'],
        'factorPreviews': {feature['id']: preview(saved['id'], factor_id=feature['id']) for feature in features},
        'tasks': contents['task_templates'],
        'targets': contents['targets'],
        'models': contents['models'],
        'eventTypes': contents['chan_event']['types'],
        'experimentFields': ExperimentIn.model_json_schema()['properties'],
    }
    fixture['trainingExample'] = None
    adapter = next((model for model in contents['models']
                    if model['input'] == 'vector' and model['available'] and 'regression' in model['tasks']), None)
    fixture['backtest'] = None
    if adapter is not None:
        submitted = create_experiment(ExperimentIn(
            name='逐 K 线收益回归', dataset_id=saved['id'], target_id='forward_return',
            model=adapter['id'], factor_ids=['momentum.rsi'], auto_backtest=False,
        ))
        worker = 'workbench-fixture'
        execute(jobs.claim(worker), worker)
        record = create_backtest(BacktestIn(name='实验预测示例回测', experiment_id=submitted['id'],
                                            run_id=submitted['latest_run_id']))
        result = record['result']
        fixture['backtest'] = {key: record[key] for key in ('name', 'source', 'config', 'metrics', 'period', 'engine_version')}
        fixture['backtest']['equity'] = [
            {'date': row['time'], 'equity': row['equity'], 'benchmark': row['benchmark']}
            for row in result['rows']
        ]
        fixture['backtest']['orders'] = result['orders'][-20:]
    example_factors = ['chan.side', 'chan.retrace']
    if adapter is not None and set(example_factors) <= {item['id'] for item in features}:
        jobs.initialize()
        submitted = create_experiment(ExperimentIn(
            name='缠论事件收益回归', dataset_id=saved['id'], sample_mode='chan_event',
            target_id='forward_return', model=adapter['id'], factor_ids=example_factors,
            auto_backtest=False,
        ))
        worker = 'workbench-fixture'
        execute(jobs.claim(worker), worker)
        completed = experiment(submitted['id'])
        result = completed.get('result') or {}
        config = completed['snapshot']['config']
        fixture['trainingExample'] = {
            'name': completed['name'], 'status': completed['status'], 'message': completed['message'],
            'model': config['model'], 'target': completed['snapshot']['target']['name'],
            'sampleMode': config['sample_mode'], 'kind': result.get('kind'),
            'metrics': {key: value['metrics'] for key, value in (result.get('diagnostics') or {}).get('splits', {}).items()
                        if value.get('metrics')},
            'counts': {key: value['count'] for key, value in result.get('splits', {}).items()},
        }
    return fixture


if __name__ == '__main__':
    destination = Path(__file__).resolve().parents[1] / 'docs/mockups/research-workbench-fixture.js'
    with TemporaryDirectory(prefix='quant-workbench-demo-') as directory:
        os.environ['QUANT_DATA_DIR'] = directory
        with redirect_stdout(sys.stderr):
            fixture = export_fixture()
    destination.parent.mkdir(parents=True, exist_ok=True)
    destination.write_text(
        '// Generated by scripts/export_workbench_demo.py.\nwindow.WORKBENCH_FIXTURE = '
        + json.dumps(fixture, ensure_ascii=False, allow_nan=False, separators=(',', ':')) + ';\n',
        encoding='utf-8',
    )
